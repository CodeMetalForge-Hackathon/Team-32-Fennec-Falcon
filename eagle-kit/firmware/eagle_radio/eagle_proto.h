// eagle_proto.h - byte layouts and radio defaults shared by the firmware and the Python kit.
//
// The CANONICAL description of every frame is the docstring of eagle/protocol.py.
// This header is duplicated in firmware/eagle_radio/ and firmware/tag/ (the Arduino IDE only
// compiles files inside the sketch folder). tests/test_firmware_layout.py fails if the two
// copies differ or if any value here disagrees with eagle/protocol.py.
#pragma once

#define EAGLE_PROTO_VERSION 1

// ---- message types ---------------------------------------------------------------------
#define MSG_CHALLENGE 0x01
#define MSG_REPLY     0x02
#define MSG_FIX       0x03
#define MSG_BEACON    0x04

#define MAC_LEN   8      // truncated HMAC-SHA256
#define NONCE_LEN 8      // counter (uint32 big-endian) || 4 random bytes

// ---- CHALLENGE (Eagle -> tag), 20 bytes ------------------------------------------------
// type | eagle_id | nonce[8] | reply_window (x10 ms) | eagle_tx_dbm (int8) | mac[8]
// mac = HMAC-SHA256(K_TAG, bytes[0..11])[0..7]
#define CHAL_OFF_TYPE   0
#define CHAL_OFF_EAGLE  1
#define CHAL_OFF_NONCE  2
#define CHAL_OFF_WINDOW 10
#define CHAL_OFF_TXDBM  11
#define CHAL_OFF_MAC    12
#define CHAL_LEN        20

// ---- REPLY (tag -> Eagle), 21 bytes ----------------------------------------------------
// type | tag_id | nonce[8] (echo) | status_wire | battery % | rssi_heard (int8) | mac[8]
// status_wire = status ^ HMAC-SHA256(K_COVERT, "EGCV" | tag_id | eagle_id | ctr_be32)[0]
// mac = HMAC-SHA256(K_TAG, bytes[0..12])[0..7]
#define REPLY_OFF_TYPE   0
#define REPLY_OFF_TAG    1
#define REPLY_OFF_NONCE  2
#define REPLY_OFF_STATUS 10
#define REPLY_OFF_BATT   11
#define REPLY_OFF_RSSI   12
#define REPLY_OFF_MAC    13
#define REPLY_LEN        21

// ---- frames the radios only relay as hex (built/checked in Python) -------------------------
#define FIX_LEN    48    // AES-256-GCM, see eagle/protocol.py
#define BEACON_LEN 15

#define COVERT_LABEL     "EGCV"
#define COVERT_LABEL_LEN 4

// ---- status bits --------------------------------------------------------------------------
#define ST_INJURED 0x01
#define ST_MOBILE  0x02
#define ST_WATER   0x04
#define ST_FOOD    0x08
#define ST_THREAT  0x10
#define ST_DURESS  0x20
#define ST_BUTTON  0x40
#define ST_LOWBATT 0x80

// ---- radio defaults (must match config/example.yaml radio.*) -----------------------------------
#define RADIO_FREQ_MHZ  915.0
#define RADIO_BW_KHZ    250.0
#define RADIO_SF        7
#define RADIO_CR        5        // 4/5
#define RADIO_SYNC_WORD 0x12     // RadioLib private sync word
#define RADIO_PREAMBLE  8
#define RADIO_MIN_DBM   (-9)     // SX1262 range in RadioLib
#define RADIO_MAX_DBM   22
#define LINK_MARGIN_DB  10
// Eagle receiver sensitivity at RADIO_SF / RADIO_BW_KHZ: -174 + 10log10(BW) + NF(6) + SNRmin
#define EAGLE_SENS_DBM  (-121.5)

