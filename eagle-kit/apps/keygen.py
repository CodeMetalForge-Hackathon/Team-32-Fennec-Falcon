#!/usr/bin/env python3
"""Generate fresh mission keys.

    python apps/keygen.py --tag-id 7 --out-dir keys/

writes  keys/eagle_keys.yaml   (tag_hmac + fix_aes, covert: null)  -> merge into each Eagle's config
        keys/nest_keys.yaml    (fix_aes + covert [+ tag_hmac])     -> the Nest's config
        keys/tag_keys.h        (TAG_ID, K_TAG, K_COVERT)           -> copy over firmware/tag/tag_keys.h
Keys come from os.urandom (32 bytes each). Keep the files off shared drives.
"""
from __future__ import annotations

import argparse
import os
from pathlib import Path


def c_array(name: str, key: bytes) -> str:
    rows = [", ".join(f"0x{b:02x}" for b in key[i:i + 16]) for i in (0, 16)]
    return f"static const uint8_t {name}[32] = {{\n  {rows[0]},\n  {rows[1]},\n}};\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--tag-id", type=int, default=7)
    ap.add_argument("--out-dir", default="keys")
    args = ap.parse_args(argv)
    k_tag, k_fix, k_cov = os.urandom(32), os.urandom(32), os.urandom(32)
    out = Path(args.out_dir)
    out.mkdir(parents=True, exist_ok=True)
    (out / "eagle_keys.yaml").write_text(
        f"keys:\n  tag_hmac: {k_tag.hex()}\n  fix_aes: {k_fix.hex()}\n  covert: null\n")
    (out / "nest_keys.yaml").write_text(
        f"keys:\n  tag_hmac: {k_tag.hex()}\n  fix_aes: {k_fix.hex()}\n  covert: {k_cov.hex()}\n")
    (out / "tag_keys.h").write_text(
        "// generated by apps/keygen.py\n#pragma once\n#include <stdint.h>\n\n"
        f"#define TAG_ID {args.tag_id}\n\n" + c_array("K_TAG", k_tag) + "\n" + c_array("K_COVERT", k_cov))
    for f in ("eagle_keys.yaml", "nest_keys.yaml", "tag_keys.h"):
        os.chmod(out / f, 0o600)
    print(f"wrote {out}/eagle_keys.yaml, nest_keys.yaml, tag_keys.h (tag id {args.tag_id})")
    print("Eagle: paste eagle_keys.yaml into its config.  Nest: nest_keys.yaml.  Tag: copy tag_keys.h "
          "to firmware/tag/ and flash.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
